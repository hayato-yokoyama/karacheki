export const themes = createThemeBuilder()
	.addPalettes(palettes)
	.addTemplates(templates)
	.addThemes({
		light: {
			template: "base",
			palette: "light",
		},
		dark: {
			template: "base",
			palette: "dark",
		},
	})
	.addChildThemes(
		palettes.light_accent
			? {
					accent: [
						{
							parent: "light",
							template: "base",
							palette: "light_accent",
						},
						{
							parent: "dark",
							template: "base",
							palette: "dark_accent",
						},
					],
				}
			: {},
	)
	.addChildThemes(defaultSubThemes)
	.addChildThemes(defaultComponentThemes, {
		avoidNestingWithin: [
			"alt1",
			"alt2",
			"surface1",
			"surface2",
			"surface3",
			"surface4",
			"active",
		],
	})

	.build();
